import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Every bounty monitor shares the acknowledged-result implementation. Runtime
// installation consumes a self-contained file at each published download URL.
const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
const check = args.includes('--check');
const moduleOption = args.indexOf('--esbuild-module');
const modulePath = moduleOption >= 0 ? args[moduleOption + 1] : undefined;
if (moduleOption >= 0 && !modulePath) throw new Error('--esbuild-module requires a local path');
const acceptedArguments = new Set(['--check', '--esbuild-module', modulePath]);
if (args.some(arg => !acceptedArguments.has(arg))) throw new Error('Unknown build argument');
const esbuild = await import(modulePath ? pathToFileURL(resolve(modulePath)).href : 'esbuild');
if (esbuild.version !== '0.21.5') throw new Error('Monitor bundles require esbuild 0.21.5');

const catalog = JSON.parse(await readFile(resolve(root, 'plugins.json'), 'utf8'));
const monitors = catalog.plugins.filter(plugin => plugin.main_category === 'bounty');
for (const plugin of monitors) {
  const { id } = plugin;
  const entry = `source/bounty/${id}/index.ts`;
  const source = await readFile(resolve(root, entry), 'utf8');
  const metadata = source.slice(0, source.indexOf('*/') + 2);
  if (!metadata.includes(`@plugin ${id}`)) throw new Error(`${id}: missing source metadata`);
  if (!metadata.includes(`@version ${plugin.version}\n`)) throw new Error(`${id}: source/catalog version differs`);
  if (!metadata.includes('monitor:results-stream-v1')) throw new Error(`${id}: source must declare monitor:results-stream-v1`);
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: [entry],
    bundle: true,
    write: false,
    platform: 'neutral',
    format: 'esm',
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    minifyWhitespace: true,
    minifyIdentifiers: false,
    minifySyntax: false,
    lineLimit: 160,
    banner: { js: `${metadata}\n// Generated by scripts/build_monitor_plugins.mjs from ${entry}; edit the source modules.` },
    footer: { js: 'globalThis.get_input_schema=get_input_schema; globalThis.get_output_schema=get_output_schema; globalThis.analyze=analyze;' },
    metafile: true,
    logLevel: 'silent',
  });
  if (Object.values(result.metafile.outputs).some(output => output.imports.length)) {
    throw new Error(`${id}: published bundle must not contain external imports`);
  }
  const output = result.outputFiles[0].text;
  if (output.split('\n').length > 2000) throw new Error(`${id}: generated bundle exceeds 2000 lines`);
  const destination = resolve(root, `plugins/bounty/${id}.ts`);
  if (check) {
    if (await readFile(destination, 'utf8') !== output) throw new Error(`${id}: generated bundle is stale`);
  } else {
    await writeFile(destination, output);
  }
  console.log(`${id}: ${check ? 'reproducible' : 'built'}, ${Object.keys(result.metafile.inputs).length} modules, ${output.split('\n').length - 1} lines`);
}
