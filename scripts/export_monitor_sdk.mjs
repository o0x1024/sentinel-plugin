import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
const check = args.includes('--check');
function option(name) {
  const index = args.indexOf(name);
  if (index < 0) return undefined;
  if (!args[index + 1] || args[index + 1].startsWith('--')) throw new Error(`${name} requires a path`);
  return args[index + 1];
}
const modulePath = option('--esbuild-module');
const authoringPath = option('--authoring-root');
const accepted = new Set(['--check', '--esbuild-module', modulePath, '--authoring-root', authoringPath]);
if (args.some(arg => !accepted.has(arg))) throw new Error('Unknown monitor SDK export argument');
const authoringRoot = resolve(authoringPath || resolve(root, '../sentinel-ai-pro/src-tauri/sentinel-plugin-authoring'));
const esbuild = await import(modulePath ? pathToFileURL(resolve(modulePath)).href : 'esbuild');
if (esbuild.version !== '0.21.5') throw new Error('Monitor SDK export requires esbuild 0.21.5');

const paths = ['source/shared/monitor_results.ts', 'source/shared/monitor_delta.ts'];
const combinedHash = createHash('sha256');
const sources = [];
for (const path of paths) {
  const source = await readFile(resolve(root, path));
  combinedHash.update(path).update('\0').update(source).update('\0');
  sources.push({ path, sha256: createHash('sha256').update(source).digest('hex'), bytes: source.length });
}
const sourcesSha256 = combinedHash.digest('hex');
const result = await esbuild.build({
  absWorkingDir: root,
  stdin: { contents: `export { createMonitorResultStream } from './source/shared/monitor_results.ts';\nexport { MONITOR_DELTA_INPUT_FIELDS } from './source/shared/monitor_delta.ts';\n`, resolveDir: root, sourcefile: 'monitor_sdk_entry.ts', loader: 'ts' },
  bundle: true, write: false, platform: 'neutral', format: 'iife', globalName: 'SENTINEL_MONITOR_RESULT_SDK',
  target: 'es2020', charset: 'utf8', legalComments: 'none', minify: false,
  banner: { js: `// Generated by sentinel-plugin/scripts/export_monitor_sdk.mjs; edit the canonical source modules.\n// canonical_sources_sha256: ${sourcesSha256}` },
  metafile: true, logLevel: 'silent',
});
if (Object.values(result.metafile.outputs).some(output => output.imports.length)) {
  throw new Error('Embedded monitor SDK must be self-contained');
}
const sdk = result.outputFiles[0].text;
if (sdk.split('\n').length > 2000) throw new Error('Embedded monitor SDK exceeds 2000 lines');
const manifest = JSON.stringify({
  format: 'sentinel-monitor-sdk/v1', esbuild: esbuild.version, namespace: 'SENTINEL_MONITOR_RESULT_SDK',
  protocol: 'monitor-results-v1', stream_tag: 'monitor:results-stream-v1',
  sources_sha256: sourcesSha256, sources,
  sdk_sha256: createHash('sha256').update(sdk).digest('hex'),
}, null, 2) + '\n';
for (const [name, content] of [['monitor_result_sdk.js', sdk], ['monitor_result_sdk.manifest.json', manifest]]) {
  const destination = resolve(authoringRoot, 'resources', name);
  if (check) {
    if (await readFile(destination, 'utf8') !== content) throw new Error(`${name}: embedded monitor SDK is stale`);
  } else {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, content);
  }
}
console.log(`monitor SDK: ${check ? 'reproducible' : 'exported'}, canonical_sha256=${sourcesSha256}, ${sdk.split('\n').length - 1} lines`);
